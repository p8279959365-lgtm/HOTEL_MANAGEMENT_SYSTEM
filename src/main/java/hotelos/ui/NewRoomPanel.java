package hotelos.ui;

import hotelos.DBConnection;

import javax.swing.*;
import javax.swing.border.EmptyBorder;
import java.awt.*;
import java.math.BigDecimal;
import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;

/** Adds newly constructed rooms to the existing room inventory. */
public class NewRoomPanel extends JPanel {
    private final JTextField roomNumber = new JTextField(18);
    private final JTextField floor = new JTextField(18);
    private final JComboBox<RoomType> roomType = new JComboBox<>();
    private final JTextField rateValue = new JTextField(18);
    private final JLabel idValue = new JLabel("Generated automatically when saved");

    public NewRoomPanel() {
        setLayout(new BorderLayout());
        setBackground(Theme.BG);
        setBorder(new EmptyBorder(0, 0, 0, 0));

        JPanel page = PanelTools.page("Add New Room", "Register newly constructed rooms in the hotel inventory.");


        JPanel card = PanelTools.card();
        card.setBorder(BorderFactory.createCompoundBorder(
                BorderFactory.createLineBorder(Theme.BORDER),
                new EmptyBorder(22, 24, 22, 24)));

        JPanel form = new JPanel(new GridBagLayout());
        form.setOpaque(false);
        GridBagConstraints gbc = new GridBagConstraints();
        gbc.insets = new Insets(9, 10, 9, 10);
        gbc.fill = GridBagConstraints.HORIZONTAL;
        gbc.weightx = 1;

        addField(form, gbc, 0, "Room number", roomNumber);
        addField(form, gbc, 1, "Room type", roomType);
        addField(form, gbc, 2, "Floor", floor);
        addField(form, gbc, 3, "Rate per night (editable)", rateValue);
        addField(form, gbc, 4, "Room ID", idValue);

        JLabel status = new JLabel("Vacant / Available (default)");
        status.setFont(Theme.BODY.deriveFont(Font.BOLD));
        status.setForeground(Theme.TEAL);
        addField(form, gbc, 5, "Initial status", status);

        roomNumber.setToolTipText("Enter the room number shown on the room door, e.g. 105");
        styleInput(roomNumber);
        styleInput(floor);
        styleCombo(roomType);
        styleInput(rateValue);
        rateValue.setToolTipText("Auto-filled from the selected room type. You can change this room's rate.");
        idValue.setForeground(Theme.MUTED);

        roomType.addActionListener(e -> updateRate());

        JPanel actions = new JPanel(new FlowLayout(FlowLayout.LEFT, 10, 8));
        actions.setOpaque(false);
        JButton save = PanelTools.button("Add Room", true);
        JButton clear = PanelTools.button("Clear Form", false);
        JButton reload = PanelTools.button("Reload Room Types", false);
        save.addActionListener(e -> saveRoom());
        clear.addActionListener(e -> clearForm());
        reload.addActionListener(e -> loadRoomTypes());
        actions.add(save);
        actions.add(clear);
        actions.add(reload);

        JLabel note = new JLabel("Room ID is generated by MySQL. The rate is pre-filled from the room type and can be customized for this room.");
        note.setForeground(Theme.MUTED);
        note.setFont(new Font("Segoe UI", Font.PLAIN, 13));

        JPanel content = new JPanel(new BorderLayout(0, 12));
        content.setOpaque(false);
        content.add(form, BorderLayout.NORTH);
        content.add(note, BorderLayout.CENTER);
        content.add(actions, BorderLayout.SOUTH);
        card.add(content, BorderLayout.NORTH);
        page.add(card, BorderLayout.CENTER);
        add(page, BorderLayout.CENTER);

        loadRoomTypes();
    }

    private void addField(JPanel form, GridBagConstraints gbc, int row, String label, Component input) {
        gbc.gridx = 0; gbc.gridy = row; gbc.weightx = 0.35;
        JLabel l = new JLabel(label);
        l.setFont(Theme.BODY.deriveFont(Font.BOLD));
        l.setForeground(Theme.TEXT);
        form.add(l, gbc);
        gbc.gridx = 1; gbc.weightx = 0.65;
        if (input instanceof JTextField field) styleInput(field);
        form.add(input, gbc);
    }

    private void styleInput(JTextField field) {
        field.setFont(Theme.BODY);
        field.setForeground(Theme.TEXT);
        field.setBackground(Theme.INPUT_BG);
        field.setCaretColor(Theme.TEXT);
        field.setBorder(BorderFactory.createCompoundBorder(
                BorderFactory.createLineBorder(Theme.BORDER), new EmptyBorder(8, 9, 8, 9)));
    }

    private void styleCombo(JComboBox<?> combo) {
        combo.setFont(Theme.BODY);
        combo.setForeground(Theme.TEXT);
        combo.setBackground(Theme.INPUT_BG);
        combo.setForeground(Theme.TEXT);
        combo.setOpaque(true);
        combo.setBorder(BorderFactory.createCompoundBorder(
                BorderFactory.createLineBorder(Theme.BORDER), new EmptyBorder(5, 7, 5, 7)));
        combo.setRenderer(new DefaultListCellRenderer() {
            @Override
            public Component getListCellRendererComponent(JList<?> list, Object value, int index,
                    boolean isSelected, boolean cellHasFocus) {
                JLabel label = (JLabel) super.getListCellRendererComponent(
                        list, value, index, isSelected, cellHasFocus);
                label.setFont(Theme.BODY);
                label.setOpaque(true);
                label.setBackground(isSelected ? Theme.TABLE_SELECTED : Theme.INPUT_BG);
                label.setForeground(Theme.TEXT);
                label.setBorder(new EmptyBorder(6, 8, 6, 8));
                return label;
            }
        });
        combo.setPreferredSize(new Dimension(260, 40));
    }

    private void loadRoomTypes() {
        roomType.removeAllItems();
        try (Connection c = DBConnection.getConnection();
             PreparedStatement ps = c.prepareStatement(
                     "SELECT type_id, type_name, price_per_night FROM room_types ORDER BY type_name");
             ResultSet rs = ps.executeQuery()) {
            while (rs.next()) {
                roomType.addItem(new RoomType(rs.getInt("type_id"), rs.getString("type_name"),
                        rs.getBigDecimal("price_per_night")));
            }
            updateRate();
            if (roomType.getItemCount() == 0) {
                JOptionPane.showMessageDialog(this,
                        "No room types found. Add a room type in the database before adding rooms.",
                        "Room Types Required", JOptionPane.WARNING_MESSAGE);
            }
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Could not load room types: " + ex.getMessage(),
                    "Database Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void updateRate() {
        RoomType selected = (RoomType) roomType.getSelectedItem();
        if (selected == null) {
            rateValue.setText("");
        } else {
            rateValue.setText(selected.rate().toPlainString());
        }
    }

    private void saveRoom() {
        String number = roomNumber.getText().trim();
        String floorText = floor.getText().trim();
        String rateText = rateValue.getText().trim();
        RoomType type = (RoomType) roomType.getSelectedItem();

        if (number.isEmpty() || floorText.isEmpty() || rateText.isEmpty() || type == null) {
            JOptionPane.showMessageDialog(this, "Enter room number, floor, rate, and select a room type.",
                    "Missing Details", JOptionPane.WARNING_MESSAGE);
            return;
        }
        int floorNumber;
        BigDecimal customRate;
        try {
            customRate = new BigDecimal(rateText);
            if (customRate.signum() <= 0) throw new NumberFormatException();
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Rate must be a valid amount greater than zero.",
                    "Invalid Rate", JOptionPane.WARNING_MESSAGE);
            return;
        }
        try {
            floorNumber = Integer.parseInt(floorText);
            if (floorNumber < 0) throw new NumberFormatException();
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Floor must be a non-negative whole number.",
                    "Invalid Floor", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try (Connection c = DBConnection.getConnection()) {
            try (PreparedStatement check = c.prepareStatement(
                    "SELECT COUNT(*) FROM rooms WHERE room_number = ?")) {
                check.setString(1, number);
                try (ResultSet rs = check.executeQuery()) {
                    rs.next();
                    if (rs.getInt(1) > 0) {
                        JOptionPane.showMessageDialog(this, "Room number " + number + " already exists.",
                                "Duplicate Room", JOptionPane.WARNING_MESSAGE);
                        return;
                    }
                }
            }
            try (PreparedStatement ps = c.prepareStatement(
                    "INSERT INTO rooms (room_number, type_id, floor, status, room_rate) VALUES (?, ?, ?, 'Available', ?)",
                    PreparedStatement.RETURN_GENERATED_KEYS)) {
                ps.setString(1, number);
                ps.setInt(2, type.id());
                ps.setInt(3, floorNumber);
                ps.setBigDecimal(4, customRate);
                ps.executeUpdate();
                try (ResultSet keys = ps.getGeneratedKeys()) {
                    String id = keys.next() ? String.valueOf(keys.getLong(1)) : "created";
                    JOptionPane.showMessageDialog(this,
                            "Room added successfully.\nRoom ID: " + id + "\nRoom: " + number
                                    + "\nRate per night: ₹" + customRate + "\nInitial status: Vacant / Available",
                            "Room Added", JOptionPane.INFORMATION_MESSAGE);
                }
            }
            clearForm();
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Could not add room: " + ex.getMessage(),
                    "Database Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void clearForm() {
        roomNumber.setText("");
        floor.setText("");
        if (roomType.getItemCount() > 0) roomType.setSelectedIndex(0);
        updateRate();
        roomNumber.requestFocusInWindow();
    }

    private record RoomType(int id, String name, BigDecimal rate) {
        @Override public String toString() { return name + " (₹" + rate + "/night)"; }
    }
}
